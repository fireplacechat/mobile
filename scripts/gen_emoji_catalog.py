"""Generate lib/src/model/chat/emoji_catalog_data.dart.

python3 scripts/gen_emoji_catalog.py EMOJI_TEST ANNOTATIONS DERIVED OUT

EMOJI_TEST is Unicode's emoji-test.txt (15.0). ANNOTATIONS and DERIVED are
CLDR's common/annotations/en.xml and common/annotationsDerived/en.xml (42).
The app never downloads these; the generated table ships with it so emoji
search works offline. Skin-tone variants are left out, and so is anything
`validReactionEmoji` (lib/src/db/message_mutation.dart) would reject: the
pattern below must stay the same as that one.
"""

import re
import sys
import xml.etree.ElementTree as ET

PICTOGRAPH = (
    "[\U0001F300-\U0001F3FA\U0001F400-\U0001FAFF☀-➿"
    "©®‼⁉™ℹ↔-⇿⌀-⏿"
    "⬀-⯿〰〽㊗㊙]"
)
MODIFIER = "️?[\U0001F3FB-\U0001F3FF]?"
VALID = re.compile(
    "^(?:" + PICTOGRAPH + MODIFIER + "(?:‍" + PICTOGRAPH + MODIFIER + ")*"
    "|[\U0001F1E6-\U0001F1FF]{2}|[0-9#*]️?⃣)$"
)
GROUPS = {
    "Smileys & Emotion": 0,
    "People & Body": 0,
    "Animals & Nature": 1,
    "Food & Drink": 2,
    "Activities": 3,
    "Travel & Places": 4,
    "Objects": 5,
    "Symbols": 6,
    "Flags": 7,
}
NAMES = [
    "Smileys & People",
    "Animals & Nature",
    "Food & Drink",
    "Activities",
    "Travel & Places",
    "Objects",
    "Symbols",
    "Flags",
]
HEADER = """// GENERATED by scripts/gen_emoji_catalog.py from Unicode emoji-test.txt 15.0 and
// CLDR 42 English annotations. Do not edit by hand. Skin-tone variants and
// sequences that reaction validation does not accept are left out.
// Data (c) Unicode, Inc., used under the Unicode License v3; see
// docs/legal/THIRD_PARTY_NOTICES.md.
// dart format off

/// One emoji per line: the emoji, its name, then search keywords, separated
/// by tabs. A line starting with '#' names the category that follows.
const emojiCatalogData = r'''
"""


def main() -> None:
    emoji_test, annotations, derived, out = sys.argv[1:5]
    keywords: dict[str, list[str]] = {}
    for path in (annotations, derived):
        for node in ET.parse(path).getroot().iter("annotation"):
            if node.get("type") != "tts":
                keywords[node.get("cp")] = [k.strip() for k in node.text.split("|")]
    categories: list[list[str]] = [[] for _ in NAMES]
    group = None
    dropped = 0
    for line in open(emoji_test, encoding="utf-8"):
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        if line.startswith("#") or "; fully-qualified" not in line:
            continue
        if group not in GROUPS:
            continue
        emoji = "".join(chr(int(c, 16)) for c in line.split(";")[0].split())
        name = re.search(r"# \S+ E\d+\.\d+ (.+)$", line.strip()).group(1).lower()
        if "skin tone" in name:
            continue
        if not VALID.match(emoji) or len(emoji.encode("utf-16-le")) // 2 > 64:
            dropped += 1
            continue
        words = [name]
        for word in keywords.get(emoji) or keywords.get(emoji.replace("️", "")) or []:
            word = word.lower()
            if word not in words:
                words.append(word)
        row = "\t".join([emoji] + words)
        if "'''" in row:
            raise SystemExit(f"cannot embed: {row}")
        categories[GROUPS[group]].append(row)
    with open(out, "w", encoding="utf-8", newline="\n") as file:
        file.write(HEADER)
        for name, rows in zip(NAMES, categories):
            file.write("#" + name + "\n")
            file.write("\n".join(rows) + "\n")
        file.write("''';\n")
    print([len(rows) for rows in categories], "dropped", dropped, file=sys.stderr)


if __name__ == "__main__":
    main()
